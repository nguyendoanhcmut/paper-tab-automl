import os
import json

output_dir = r"C:\Users\Admin\.gemini\antigravity\scratch\mbr_opcond_survey\branches_v2\L-02"
manifest_path = os.path.join(output_dir, "L-02_scout_manifest.json")

with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = json.load(f)

context_pack = manifest.get("global_context_pack", "")
routing = manifest.get("routing_table", [])

subagents = []
for chunk in routing:
    cid = chunk["chunk_id"]
    title = chunk["title"]
    start_level = chunk["start_heading_level"]
    assigned_figs = chunk.get("figure_ids", [])
    fragment_file = chunk["fragment_file"]
    sec_file = chunk["section_text_file"]
    
    heading_prefix = "#" * start_level
    
    fig_instruction = ""
    if assigned_figs:
        fig_instruction = f"""Figures to embed in this section: {assigned_figs}.
For each figure in {assigned_figs}:
- Read evidence block from `{output_dir}\\fragments\\_fig_<fig_id>.md` (which was already generated by figure_driller), or use its content.
- Format the figure block strictly matching regex `* **Hình N.**` or `* **Bảng N.**` immediately preceding the image asset:
    * **Hình N.** [Tiêu đề hình]
      * <img src="assets/..." alt="Hình N" />
      * **Hình này chứng minh điều gì**
        * ...
      * **Từ đâu mà thấy được**
        * ...
  (Đối với bảng dùng `* **Bảng N.**` và `* **Bảng này chứng minh điều gì**`).
- Embed it under the specific claim bullet that cites or discusses it. Keep within 10 lines."""
    else:
        fig_instruction = "No figures assigned to this chunk."

    prompt = f"""You are branch_driller for chunk {cid}: {title}.

Parameters:
- output_dir: {output_dir}
- chunk_id: {cid}
- section_text_file: {sec_file}
- section_title: "{title}"
- start_level: {start_level}
- max_heading_level: 4
- drill_threshold_words: 800
- figures_manifest: {output_dir}\\figures_manifest.json
- assigned_figures: {assigned_figs}
- exercises: []
- domain: general
- output_language: vi
- output_file: {output_dir}\\{fragment_file}

Global context pack:
{context_pack}

Instructions:
1. Read section_text_file: `{sec_file}`.
2. Write deep, comprehensive subtree in Vietnamese to `{output_dir}\\{fragment_file}`.
   - Start with heading `{heading_prefix} {title}`.
   - Child headings can go up to H4. Deeper detail must be nested claim bullets (`* `).
   - Never write an H1 heading.
   - Extract ALL numerical values, experimental parameters, datasets, mathematical formulas, evaluation metrics (Accuracy, RMSE, MAE, R^2, ROC-AUC, Kendall tau), hyperparameter configurations, ablation findings, and case study details into granular claim bullets.
   - Wrap numbers, formulas, and units in KaTeX ($...$).
   - Keep technical terms as written, with Vietnamese translations in parentheses where appropriate.
3. Figure embedding:
{fig_instruction}
4. When finished, send to parent: Driller done. {output_dir}\\{fragment_file}. Headings: 1. Figures: {len(assigned_figs)}. Exercises: 0 (0 passed). FV: 1.0. Open: none."""

    subagents.append({
        "Model": "flash",
        "Prompt": prompt,
        "Role": f"Driller {cid} {title[:30]}",
        "TypeName": "branch_driller",
        "Workspace": "inherit",
        "scope": cid,
        "chunk_id": cid
    })

specs_file = os.path.join(output_dir, "driller_subagents.json")
with open(specs_file, "w", encoding="utf-8") as f:
    json.dump(subagents, f, indent=2, ensure_ascii=False)

print(f"Generated {len(subagents)} driller specs in {specs_file}")
